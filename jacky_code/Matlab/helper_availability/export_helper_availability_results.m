function summaryTable = export_helper_availability_results(caseResults, cfg)
% export_helper_availability_results
% Build the final three-row summary table and write it to
%   results/helper_availability_summary.csv
%   results/helper_availability_summary.xlsx
%   results/helper_availability_summary.tex
%   results/helper_availability_raw.mat
%
% Inputs:
%   caseResults : 1 x N cell of run_constellation_case outputs
%   cfg         : full config (for cfg.io paths and caption)
%
% Output:
%   summaryTable : the MATLAB table that was written
%
% Averages and percentages are shown to two decimal places. All raw
% per-slot records are stored in the .mat file.

resultsDir = cfg.io.resultsDir;
if ~exist(resultsDir, 'dir')
    mkdir(resultsDir);
end

N = numel(caseResults);
Geometry = strings(N, 1);
AvgCriticalSatellitesPerCriticalSlot = zeros(N, 1);
AvgRecoveryCapableHelpersPerCriticalSatellite = zeros(N, 1);
HelperAvailabilityRatioPercent = zeros(N, 1);
ClosedBeamHelperCoverageRatioPercent = zeros(N, 1);

for i = 1:N
    m = caseResults{i}.metrics;
    Geometry(i) = string(caseResults{i}.name);
    AvgCriticalSatellitesPerCriticalSlot(i) = round(m.AvgCriticalSatellitesPerCriticalSlot, 2);
    AvgRecoveryCapableHelpersPerCriticalSatellite(i) = round(m.AvgRecoveryCapableHelpersPerCriticalSatellite, 2);
    HelperAvailabilityRatioPercent(i) = round(m.HelperAvailabilityRatioPercent, 2);
    ClosedBeamHelperCoverageRatioPercent(i) = round(m.ClosedBeamHelperCoverageRatioPercent, 2);
end

summaryTable = table(Geometry, AvgCriticalSatellitesPerCriticalSlot, ...
    AvgRecoveryCapableHelpersPerCriticalSatellite, HelperAvailabilityRatioPercent, ...
    ClosedBeamHelperCoverageRatioPercent);

csvPath = fullfile(resultsDir, [cfg.io.summaryBase '.csv']);
xlsxPath = fullfile(resultsDir, [cfg.io.summaryBase '.xlsx']);
texPath = fullfile(resultsDir, [cfg.io.summaryBase '.tex']);
matPath = fullfile(resultsDir, cfg.io.rawMat);

writetable(summaryTable, csvPath);
if exist(xlsxPath, 'file'); delete(xlsxPath); end
writetable(summaryTable, xlsxPath);
write_latex_table(texPath, summaryTable, cfg.io.texCaption);

rawResults = caseResults; %#ok<NASGU>
commonUsed = cfg.common;   %#ok<NASGU>
save(matPath, 'rawResults', 'commonUsed', 'summaryTable');

fprintf('Saved summary: %s\n', csvPath);
fprintf('Saved summary: %s\n', xlsxPath);
fprintf('Saved summary: %s\n', texPath);
fprintf('Saved raw records: %s\n', matPath);
end

function write_latex_table(texPath, T, caption)
% Write a booktabs-style LaTeX table with the required display header.
fid = fopen(texPath, 'w', 'n', 'UTF-8');
if fid < 0
    warning('export_helper_availability_results:tex', ...
        'Could not open %s for writing.', texPath);
    return;
end
c = onCleanup(@() fclose(fid));

fprintf(fid, '%% Auto-generated by export_helper_availability_results.m\n');
fprintf(fid, '\\begin{table}[t]\n\\centering\n');
fprintf(fid, '\\caption{%s}\n', caption);
fprintf(fid, '\\label{tab:helper_availability}\n');
fprintf(fid, '\\begin{tabular}{lcccc}\n\\hline\n');
fprintf(fid, ['Geometry & Avg. critical satellites per critical slot & ', ...
    'Avg. recovery-capable helpers per critical satellite & ', ...
    'Helper-availability ratio & Closed-beam helper-coverage ratio \\\\\n\\hline\n']);
for i = 1:height(T)
    fprintf(fid, '%s & %.2f & %.2f & %.2f\\%% & %.2f\\%% \\\\\n', ...
        T.Geometry(i), ...
        T.AvgCriticalSatellitesPerCriticalSlot(i), ...
        T.AvgRecoveryCapableHelpersPerCriticalSatellite(i), ...
        T.HelperAvailabilityRatioPercent(i), ...
        T.ClosedBeamHelperCoverageRatioPercent(i));
end
fprintf(fid, '\\hline\n\\end{tabular}\n\\end{table}\n');
end
